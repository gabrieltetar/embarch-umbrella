//! The development Core `deploy-core` installs beside the service (decision
//! 68).
//!
//! Everything here is pure or runs against two small traits ([`CoreApi`] for
//! the Core's HTTP face, [`Host`] for the Windows side), so each script is
//! golden-tested and each sequence is tested against fakes. Nothing in this
//! module writes the service's registration or binary: the service stays
//! registered and stopped, and `--restore-service` starts it again.

use std::time::Duration;

/// Where the development Core lives, in Windows form, under the engineer's
/// `%LOCALAPPDATA%` (`embarch-core-client`'s token discovery reads the same
/// folder, so the development Core's token pair is found without a flag).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DevLayout {
    /// `%LOCALAPPDATA%\embarch\dev` — Core's `--store`.
    pub store: String,
    /// `%LOCALAPPDATA%\embarch\dev\core\embarch-core.exe`.
    pub exe: String,
}

pub fn dev_layout(local_appdata: &str) -> DevLayout {
    let store = format!(r"{}\embarch\dev", local_appdata.trim_end_matches('\\'));
    let exe = format!(r"{store}\core\embarch-core.exe");
    DevLayout { store, exe }
}

/// Elevated: stop the service and wait for `STOPPED` (the SCM reports the
/// request, not its completion). Logs from inside the elevated context.
pub fn stop_service_script(service: &str, log: &str) -> String {
    service_script("stop", service, log, "STOPPED")
}

/// Elevated: start the service again, for `--restore-service`.
pub fn start_service_script(service: &str, log: &str) -> String {
    service_script("start", service, log, "RUNNING")
}

fn service_script(verb: &str, service: &str, log: &str, wait_for: &str) -> String {
    format!(
        "# Generated by `embarch deploy-core` (embarch-umbrella decision 68).\n\
         # Runs elevated and only {verb}s the service: its registration and\n\
         # its binary are never written.\n\
         $ErrorActionPreference = 'Stop'\n\
         $log = '{log}'\n\
         function Say($m) {{ $m | Tee-Object -FilePath $log -Append }}\n\
         Set-Content -Path $log -Value '=== embarch deploy-core: {verb} service ==='\n\
         try {{\n\
         \x20 Say '{verb} {service}'\n\
         \x20 & sc.exe {verb} {service} 2>&1 | Tee-Object -FilePath $log -Append\n\
         \x20 for ($i = 0; $i -lt 30; $i++) {{\n\
         \x20   $s = (& sc.exe query {service}) -join ' '\n\
         \x20   if ($s -match '{wait_for}') {{ break }}\n\
         \x20   Start-Sleep -Milliseconds 500\n\
         \x20 }}\n\
         \x20 & sc.exe query {service} 2>&1 | Tee-Object -FilePath $log -Append\n\
         }} catch {{\n\
         \x20 Say \"FAILED: $_\"\n\
         \x20 exit 1\n\
         }}\n\
         Say '=== done ==='\n"
    )
}

/// Unelevated: start the development Core hidden in the logon session and
/// print `PID <n>`. `bind` is the service's registered `--bind`, when it has
/// one.
pub fn start_dev_script(layout: &DevLayout, bind: Option<&str>) -> String {
    let bind_args = bind.map(|b| format!(",'--bind','{b}'")).unwrap_or_default();
    format!(
        "$ErrorActionPreference = 'Stop'\n\
         $p = Start-Process -FilePath '{exe}' -ArgumentList 'run','--store','\"{store}\"'{bind_args} \
         -WindowStyle Hidden -PassThru\n\
         Write-Output ('PID ' + $p.Id)\n",
        exe = layout.exe,
        store = layout.store,
    )
}

/// Unelevated: stop the development Core **by the PID `deploy-core`
/// recorded**, never by name, and only if that PID is still our binary (a
/// recycled PID must not take another process down).
pub fn stop_dev_script(pid: u32, layout: &DevLayout) -> String {
    format!(
        "$p = Get-Process -Id {pid} -ErrorAction SilentlyContinue\n\
         if ($p -and $p.Path -eq '{exe}') {{\n\
         \x20 Stop-Process -Id {pid}\n\
         \x20 $p.WaitForExit(15000) | Out-Null\n\
         \x20 Write-Output 'stopped'\n\
         }} else {{\n\
         \x20 Write-Output 'not running'\n\
         }}\n",
        exe = layout.exe,
    )
}

/// Parses the `PID <n>` line [`start_dev_script`] prints.
pub fn parse_pid(stdout: &str) -> Option<u32> {
    stdout.lines().find_map(|l| l.trim().strip_prefix("PID ")?.trim().parse().ok())
}

/// The fields of `/status` this module reads. Missing ones are `None`, never
/// invented.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct StatusView {
    pub mode: Option<String>,
    pub binary_sha256: Option<String>,
    pub study_in_flight: Option<String>,
    pub keyid: Option<String>,
}

pub fn parse_status(body: &str) -> Result<StatusView, String> {
    let v: serde_json::Value = serde_json::from_str(body).map_err(|e| format!("/status is not JSON: {e}"))?;
    let s = |k: &str| v.get(k).and_then(|x| x.as_str()).map(str::to_string);
    Ok(StatusView {
        mode: s("mode"),
        binary_sha256: s("binary_sha256"),
        study_in_flight: s("study_in_flight"),
        keyid: s("keyid"),
    })
}

/// Core's HTTP face, as this module needs it.
pub trait CoreApi {
    async fn status(&self) -> Result<StatusView, String>;
    /// `POST /study/{id}/cancel`.
    async fn cancel_study(&self, id: &str) -> Result<(), String>;
}

/// The Windows side: scripts and the one file copy.
pub trait Host {
    /// Runs a script and returns its output (the transcript when elevated).
    fn run_script(&self, script: &str, elevated: bool) -> Result<String, String>;
    /// Copies the build to the development Core's exe path and returns the
    /// copy's SHA-256.
    fn install_copy(&self) -> Result<[u8; 32], String>;
}

/// How long and how often to wait for Core to say something.
#[derive(Debug, Clone, Copy)]
pub struct Waits {
    pub attempts: u32,
    pub interval: Duration,
}

pub fn hex(d: &[u8; 32]) -> String {
    d.iter().map(|b| format!("{b:02x}")).collect()
}

/// A study in flight refuses the deploy unless `cancel_run`, which cancels it
/// first and waits for Core to say it is idle.
pub async fn clear_study<A: CoreApi>(api: &A, cancel_run: bool, w: Waits) -> Result<(), String> {
    let Some(id) = api.status().await?.study_in_flight else {
        return Ok(());
    };
    if !cancel_run {
        return Err(format!(
            "study {id} is in flight; deploying now would stop the Core running it. Cancel it, or \
             re-run with --cancel-run"
        ));
    }
    api.cancel_study(&id).await?;
    for _ in 0..w.attempts {
        if api.status().await?.study_in_flight.is_none() {
            return Ok(());
        }
        tokio::time::sleep(w.interval).await;
    }
    Err(format!("study {id} was told to cancel but is still in flight"))
}

/// The hash check: the build, the copy, and (when given) what the running
/// development Core says it is.
pub fn check_hashes(built: &[u8; 32], copy: &[u8; 32], running: Option<&str>) -> Result<(), String> {
    if !crate::deploy::landed(*built, *copy) {
        return Err(format!("the copy ({}) is not the build ({})", hex(copy), hex(built)));
    }
    if let Some(r) = running {
        if !r.eq_ignore_ascii_case(&hex(built)) {
            return Err(format!(
                "the running development Core reports binary_sha256 {r}, not the build's {}",
                hex(built)
            ));
        }
    }
    Ok(())
}

/// Polls `/status` until `want` accepts it.
pub async fn wait_status<A: CoreApi>(
    api: &A,
    w: Waits,
    what: &str,
    want: impl Fn(&StatusView) -> bool,
) -> Result<StatusView, String> {
    let mut last = String::from("no answer");
    for _ in 0..w.attempts {
        match api.status().await {
            Ok(s) if want(&s) => return Ok(s),
            Ok(s) => last = format!("{s:?}"),
            Err(e) => last = e,
        }
        tokio::time::sleep(w.interval).await;
    }
    Err(format!("timed out waiting for {what}; last /status: {last}"))
}

/// Lowercase hex with separators dropped, so `AB:cd` and `abcd` compare equal.
pub fn normalise_fingerprint(s: &str) -> String {
    s.chars().filter(char::is_ascii_hexdigit).collect::<String>().to_ascii_lowercase()
}

pub struct InstallInputs<'a> {
    pub layout: &'a DevLayout,
    pub service: &'a str,
    pub service_running: bool,
    pub bind: Option<&'a str>,
    pub built: [u8; 32],
    pub recorded_pid: Option<u32>,
    pub cancel_run: bool,
    pub waits: Waits,
    pub elevated_log: &'a str,
}

/// Install the development Core: clear any study, stop the service (one
/// elevation), stop the previous development Core by recorded PID, copy,
/// check the copy, start, and wait for `/status` to read `development` with
/// the build's hash. Returns the new PID.
pub async fn install_development<A: CoreApi, H: Host>(
    api: &A,
    host: &H,
    i: &InstallInputs<'_>,
) -> Result<u32, String> {
    if i.service_running || i.recorded_pid.is_some() {
        // Only ask Core about a study when something is answering.
        clear_study(api, i.cancel_run, i.waits).await?;
    }
    if i.service_running {
        host.run_script(&stop_service_script(i.service, i.elevated_log), true)?;
    }
    if let Some(pid) = i.recorded_pid {
        host.run_script(&stop_dev_script(pid, i.layout), false)?;
    }
    let copy = host.install_copy()?;
    check_hashes(&i.built, &copy, None)?;
    let out = host.run_script(&start_dev_script(i.layout, i.bind), false)?;
    let pid = parse_pid(&out).ok_or_else(|| format!("the start script printed no PID: {out}"))?;
    let want = hex(&i.built);
    wait_status(api, i.waits, "the development Core", |s| {
        s.mode.as_deref() == Some("development")
            && s.binary_sha256.as_deref().is_some_and(|h| h.eq_ignore_ascii_case(&want))
    })
    .await
    .map_err(|e| format!("{e} — the running development Core's hash must equal the build's"))?;
    Ok(pid)
}

/// `--restore-service`: stop the development Core by PID, start the service,
/// and wait for `/status` to read `service` with a `keyid` matching the
/// recorded `core-fingerprint`.
#[allow(clippy::too_many_arguments)]
pub async fn restore_service<A: CoreApi, H: Host>(
    api: &A,
    host: &H,
    layout: &DevLayout,
    service: &str,
    recorded_pid: Option<u32>,
    fingerprint: &str,
    waits: Waits,
    elevated_log: &str,
) -> Result<(), String> {
    if let Some(pid) = recorded_pid {
        host.run_script(&stop_dev_script(pid, layout), false)?;
    }
    host.run_script(&start_service_script(service, elevated_log), true)?;
    let want = normalise_fingerprint(fingerprint);
    wait_status(api, waits, "the service", |s| {
        s.mode.as_deref() == Some("service")
            && s.keyid.as_deref().is_some_and(|k| normalise_fingerprint(k) == want)
    })
    .await
    .map(|_| ())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::cell::RefCell;

    const WAITS: Waits = Waits { attempts: 3, interval: Duration::ZERO };
    const BUILT: [u8; 32] = [7; 32];

    fn layout() -> DevLayout {
        dev_layout(r"C:\Users\me\AppData\Local")
    }

    #[derive(Default)]
    struct FakeCore {
        statuses: RefCell<Vec<StatusView>>,
        cancelled: RefCell<Vec<String>>,
    }
    impl FakeCore {
        fn with(statuses: Vec<StatusView>) -> Self {
            Self { statuses: RefCell::new(statuses), cancelled: RefCell::default() }
        }
    }
    impl CoreApi for FakeCore {
        async fn status(&self) -> Result<StatusView, String> {
            let mut q = self.statuses.borrow_mut();
            if q.len() > 1 { Ok(q.remove(0)) } else { q.first().cloned().ok_or_else(|| "down".into()) }
        }
        async fn cancel_study(&self, id: &str) -> Result<(), String> {
            self.cancelled.borrow_mut().push(id.to_string());
            Ok(())
        }
    }

    struct FakeHost {
        scripts: RefCell<Vec<(String, bool)>>,
        copy: [u8; 32],
    }
    impl FakeHost {
        fn new(copy: [u8; 32]) -> Self {
            Self { scripts: RefCell::default(), copy }
        }
    }
    impl Host for FakeHost {
        fn run_script(&self, script: &str, elevated: bool) -> Result<String, String> {
            self.scripts.borrow_mut().push((script.to_string(), elevated));
            Ok(if script.contains("Start-Process -FilePath") { "PID 1234\n".into() } else { "ok".into() })
        }
        fn install_copy(&self) -> Result<[u8; 32], String> {
            Ok(self.copy)
        }
    }

    fn st(mode: &str, hash: Option<&str>, study: Option<&str>) -> StatusView {
        StatusView {
            mode: Some(mode.into()),
            binary_sha256: hash.map(str::to_string),
            study_in_flight: study.map(str::to_string),
            keyid: Some("AB:cd".into()),
        }
    }

    fn inputs<'a>(l: &'a DevLayout, cancel: bool) -> InstallInputs<'a> {
        InstallInputs {
            layout: l,
            service: "com.embarch.core",
            service_running: true,
            bind: Some("0.0.0.0"),
            built: BUILT,
            recorded_pid: Some(99),
            cancel_run: cancel,
            waits: WAITS,
            elevated_log: r"C:\t\log",
        }
    }

    #[test]
    fn layout_is_under_local_appdata() {
        let l = layout();
        assert_eq!(l.store, r"C:\Users\me\AppData\Local\embarch\dev");
        assert_eq!(l.exe, r"C:\Users\me\AppData\Local\embarch\dev\core\embarch-core.exe");
    }

    #[test]
    fn stop_service_script_is_golden() {
        let s = stop_service_script("com.embarch.core", r"C:\t\log");
        assert!(s.contains("& sc.exe stop com.embarch.core"));
        assert!(s.contains("-match 'STOPPED'"));
        assert!(!s.contains("Copy-Item") && !s.contains("sc.exe config") && !s.contains("sc.exe create"));
        assert!(s.contains("Say 'stop com.embarch.core'"));
    }

    #[test]
    fn start_service_script_waits_for_running() {
        let s = start_service_script("com.embarch.core", r"C:\t\log");
        assert!(s.contains("& sc.exe start com.embarch.core"));
        assert!(s.contains("-match 'RUNNING'"));
    }

    #[test]
    fn start_dev_script_is_golden() {
        let s = start_dev_script(&layout(), Some("0.0.0.0"));
        assert_eq!(
            s,
            "$ErrorActionPreference = 'Stop'\n\
             $p = Start-Process -FilePath 'C:\\Users\\me\\AppData\\Local\\embarch\\dev\\core\\embarch-core.exe' \
             -ArgumentList 'run','--store','\"C:\\Users\\me\\AppData\\Local\\embarch\\dev\"','--bind','0.0.0.0' \
             -WindowStyle Hidden -PassThru\n\
             Write-Output ('PID ' + $p.Id)\n"
        );
        assert!(!start_dev_script(&layout(), None).contains("--bind"));
    }

    #[test]
    fn stop_dev_script_goes_by_pid_never_by_name() {
        let s = stop_dev_script(99, &layout());
        assert!(s.contains("Get-Process -Id 99"));
        assert!(s.contains("Stop-Process -Id 99"));
        assert!(!s.contains("-Name") && !s.contains("taskkill") && !s.contains("embarch-core -"));
        assert!(s.contains("$p.Path -eq"), "a recycled PID must not be killed");
    }

    #[test]
    fn pid_parses() {
        assert_eq!(parse_pid("noise\nPID 4321\n"), Some(4321));
        assert_eq!(parse_pid("nothing"), None);
    }

    #[test]
    fn status_parses_the_documented_fields_and_never_invents() {
        let v = parse_status(r#"{"mode":"development","binary_sha256":"ab","study_in_flight":null,"keyid":"k"}"#).unwrap();
        assert_eq!(v.mode.as_deref(), Some("development"));
        assert_eq!(v.study_in_flight, None);
        assert_eq!(parse_status("{}").unwrap(), StatusView::default());
    }

    #[tokio::test]
    async fn a_study_in_flight_refuses_without_cancel_run() {
        let core = FakeCore::with(vec![st("service", None, Some("s1"))]);
        let host = FakeHost::new(BUILT);
        let l = layout();
        let err = install_development(&core, &host, &inputs(&l, false)).await.unwrap_err();
        assert!(err.contains("--cancel-run"), "{err}");
        assert!(core.cancelled.borrow().is_empty());
        assert!(host.scripts.borrow().is_empty(), "nothing is stopped while a run holds the lease");
    }

    #[tokio::test]
    async fn cancel_run_cancels_the_study_first() {
        let core = FakeCore::with(vec![
            st("service", None, Some("s1")),
            st("service", None, Some("s1")),
            st("service", None, None),
            st("development", Some(&hex(&BUILT)), None),
        ]);
        let host = FakeHost::new(BUILT);
        let l = layout();
        let pid = install_development(&core, &host, &inputs(&l, true)).await.unwrap();
        assert_eq!(pid, 1234);
        assert_eq!(*core.cancelled.borrow(), vec!["s1".to_string()]);
        let scripts = host.scripts.borrow();
        assert!(scripts[0].1 && scripts[0].0.contains("sc.exe stop"), "the one elevation stops the service");
        assert!(scripts[1].0.contains("Stop-Process -Id 99"));
        assert!(scripts[2].0.contains("Start-Process"));
        assert_eq!(scripts.iter().filter(|s| s.1).count(), 1);
    }

    #[tokio::test]
    async fn a_running_core_with_another_hash_fails_the_check() {
        let core = FakeCore::with(vec![
            st("service", None, None),
            st("development", Some(&hex(&[9; 32])), None),
        ]);
        let host = FakeHost::new(BUILT);
        let l = layout();
        let err = install_development(&core, &host, &inputs(&l, false)).await.unwrap_err();
        assert!(err.contains("timed out"), "{err}");
    }

    #[test]
    fn the_hash_check_fails_on_each_mismatch() {
        let h = hex(&BUILT);
        assert!(check_hashes(&BUILT, &BUILT, Some(&h.to_uppercase())).is_ok());
        assert!(check_hashes(&BUILT, &[1; 32], None).is_err());
        assert!(check_hashes(&BUILT, &BUILT, Some(&hex(&[2; 32]))).unwrap_err().contains("running development Core"));
    }

    #[tokio::test]
    async fn a_bad_copy_stops_before_the_start() {
        let core = FakeCore::with(vec![st("service", None, None)]);
        let host = FakeHost::new([1; 32]);
        let l = layout();
        assert!(install_development(&core, &host, &inputs(&l, false)).await.is_err());
        assert!(!host.scripts.borrow().iter().any(|s| s.0.contains("Start-Process")));
    }

    /// The service's registration and binary are never written: no script
    /// this module builds names the service's binary, copies over anything,
    /// or reconfigures the service.
    #[tokio::test]
    async fn no_step_writes_the_services_registered_binary() {
        let service_exe = r"C:\Users\x\embarch-setup\embarch-core.exe";
        let core = FakeCore::with(vec![
            st("service", None, None),
            st("development", Some(&hex(&BUILT)), None),
            st("service", None, None),
        ]);
        let host = FakeHost::new(BUILT);
        let l = layout();
        install_development(&core, &host, &inputs(&l, false)).await.unwrap();
        restore_service(&FakeCore::with(vec![st("service", None, None)]), &host, &l, "com.embarch.core", Some(1234), "abcd", WAITS, "l")
            .await
            .unwrap();
        for (script, _) in host.scripts.borrow().iter() {
            assert!(!script.contains(service_exe));
            for banned in ["Copy-Item", "Set-Content -Path 'C:\\Users\\x", "sc.exe config", "sc.exe create", "sc.exe delete", ".bak-deploy"] {
                assert!(!script.replace("Set-Content -Path $log", "").contains(banned), "{banned} in {script}");
            }
        }
    }

    #[tokio::test]
    async fn restore_waits_for_service_mode_and_the_fingerprint() {
        let l = layout();
        let host = FakeHost::new(BUILT);
        let ok = FakeCore::with(vec![st("development", None, None), st("service", None, None)]);
        restore_service(&ok, &host, &l, "svc", Some(5), "ab:CD", WAITS, "l").await.unwrap();
        {
            let s = host.scripts.borrow();
            assert!(s[0].0.contains("Stop-Process -Id 5") && s[1].0.contains("sc.exe start"));
        }
        let wrong = FakeCore::with(vec![st("service", None, None)]);
        let err = restore_service(&wrong, &host, &l, "svc", None, "ffff", WAITS, "l").await.unwrap_err();
        assert!(err.contains("timed out"), "{err}");
    }

    #[test]
    fn fingerprints_compare_without_separators_or_case() {
        assert_eq!(normalise_fingerprint("AB:cd 01"), "abcd01");
    }
}
